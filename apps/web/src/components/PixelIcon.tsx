export type PixelIconName = keyof typeof GLYPHS;

function toPath(rows: string[]): string {
  let path = "";
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length; x += 1) {
      if (row.charAt(x) === "#") path += `M${x} ${y}h1v1h-1z`;
    }
  });
  return path;
}

export function PixelIcon({ name, className }: { name: PixelIconName; className?: string }) {
  // Las filas que pasan de 8 alargan el icono hacia abajo, con el mismo tamaño de píxel.
  const rows = Math.max(8, GLYPHS[name].length);
  return (
    <svg
      className={className}
      viewBox={`0 0 8 ${String(rows)}`}
      width="1em"
      height={`${String(rows / 8)}em`}
      fill="currentColor"
      shapeRendering="crispEdges"
      aria-hidden="true"
      focusable="false"
    >
      <path d={toPath(GLYPHS[name])} />
    </svg>
  );
}
